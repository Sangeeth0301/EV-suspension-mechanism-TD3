n_ok = 0;
for k = 1:numel(blocks)
    nm = blocks{k};
    set_param(B(nm), 'Description', J(nm));          % justification on the block
    if inject_code(model, nm, codes.(nm)), n_ok = n_ok + 1; end
end
fprintf('    [+] %d/%d block scripts injected.\n', n_ok, numel(blocks));
if n_ok < numel(blocks)
    outdir = fullfile(script_dir,'block_code');
    if ~exist(outdir,'dir'), mkdir(outdir); end
    for k = 1:numel(blocks)
        fid = fopen(fullfile(outdir,[blocks{k} '.m']),'w');
        fprintf(fid,'%s',codes.(blocks{k})); fclose(fid);
    end
    fprintf('    [!] Auto-inject incomplete. Code written to scripts/block_code/\n');
    fprintf('    [!] Open each block and paste the matching file.\n');
end

