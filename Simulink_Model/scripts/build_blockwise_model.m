function c = code_lpv(p, Ks, Kr, Krd)
c = sprintf([ ...
'function [u_cmd_f, u_cmd_r] = LPV_Controller(err, rho, rho_dot, mode)\n' ...
'%%#codegen\n' ...
'%% Polytopic gain scheduling between two CARE vertex gains + rho_dot feedforward.\n' ...
'%% err = 0 - x_hat from the summing junction (regulator: reference is zero).\n' ...
'a=%.4f; b=%.4f; umax=%.4f;\n' ...
'Ks = [%s];\n' ...
'Kr = [%s];\n' ...
'Krd = [%s];\n' ...
'xh = -err;   %% recover the estimated state from the error signal\n' ...
'zsf = xh(1) - a*xh(2); zsfd = xh(5) - a*xh(6);\n' ...
'qcf = [zsf - xh(3); zsfd; 0; xh(7)];\n' ...
'zsr = xh(1) + b*xh(2); zsrd = xh(5) + b*xh(6);\n' ...
'qcr = [zsr - xh(4); zsrd; 0; xh(8)];\n' ...
