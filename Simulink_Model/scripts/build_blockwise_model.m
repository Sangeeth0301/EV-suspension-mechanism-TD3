%% ======================== LOCAL HELPER FUNCTIONS ========================
function mkfun(path_, pos)
    add_block('simulink/User-Defined Functions/MATLAB Function', path_, 'Position', pos);
end

function note(model, txt, pos)
% Add an on-canvas annotation. The annotation API differs across releases,
% so try the modern object API first and fall back to the legacy block.
% Annotations are cosmetic - never let them abort the build.
    try
        an = Simulink.Annotation([model '/' txt(1:min(24,end))]);
        an.position = pos;
        an.FontSize = 10;
    catch
        try
            h = add_block('built-in/Note', ...
                [model '/note' num2str(randi(1e9))], 'Position', pos);
            set_param(h, 'Text', txt, 'FontSize','10');
        catch
            % Annotation unsupported on this release - skip silently.
        end
    end
end

function ok = inject_code(model, blockname, code)
    ok = false;
    try
        rt = sfroot();
        ch = rt.find('-isa','Stateflow.EMChart');
        tgt = [model '/' blockname];
        for i = 1:numel(ch)
            if strcmp(ch(i).Path, tgt)
                ch(i).Script = code; ok = true; return;
            end
        end
    catch
        ok = false;
    end
end

function P = care_nt2(A,B,Q,R)
    n = size(A,1); H = [A, -B*(1/R)*B'; -Q, -A'];
    [V,D] = eig(H); ev = diag(D);
    [~,ix] = sort(real(ev)); V = V(:,ix);
    X1 = V(1:n,1:n); X2 = V(n+1:end,1:n);
    P = real(X2/X1); P = (P+P')/2;
end

%% ---- Per-block code generators ----
function c = code_plant(p)
c = sprintf([ ...
'function [x_out, accel] = HalfCar_Plant(t_in, w_f, w_r, u_f, u_r)\n' ...
'%%#codegen\n' ...
'%% 4-DOF half-car plant. RK4, fixed step. See block Description for justification.\n' ...
'persistent x\n' ...
'ms=%.4f; Ip=%.4f; a=%.4f; b=%.4f; muf=%.4f; mur=%.4f;\n' ...
'ksf=%.2f; ksr=%.2f; csf=%.2f; csr=%.2f; ktf=%.2f; ktr=%.2f;\n' ...
'kem=%.4f; idc=%.4f; pp=%d; whr=%.4f; vms=%.4f;\n' ...
'sm=%.6f; kbs=%.6e; dt=%.6f;\n' ...
'if isempty(x) || t_in < dt/2\n' ...
